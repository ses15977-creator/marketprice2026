-- MarketPrice 2026: run once in the Supabase SQL Editor.
-- Public visitors can read observations. Only approved admins can edit.
create table if not exists public.platforms (
  id bigint generated by default as identity primary key,
  name text not null unique,
  event_name text,
  integration_status text not null default 'unconnected'
);
create table if not exists public.schedules (
  id bigint generated by default as identity primary key,
  platform_id bigint not null references public.platforms(id),
  label text not null,
  start_time time not null,
  verified boolean not null default false,
  active boolean not null default true
);
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  brand text,
  category text,
  variant text,
  pack_count integer
);
create table if not exists public.offers (
  id bigint generated by default as identity primary key,
  platform_id bigint not null references public.platforms(id),
  product_id bigint references public.products(id),
  listing_title text,
  seller_name text,
  url text,
  is_deal boolean not null default false
);
create table if not exists public.observations (
  id bigint generated by default as identity primary key,
  offer_id bigint not null references public.offers(id),
  seller_price numeric(14,2) not null check (seller_price >= 0),
  shipping_fee numeric(14,2) not null default 0 check (shipping_fee >= 0),
  source_url text,
  observed_at timestamptz not null default now()
);
create table if not exists public.rank_observations (
  id bigint generated by default as identity primary key,
  offer_id bigint not null references public.offers(id),
  rank integer not null check (rank between 1 and 10),
  observed_at timestamptz not null default now()
);
create table if not exists public.collection_runs (
  id bigint generated by default as identity primary key,
  platform_id bigint references public.platforms(id),
  status text not null,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  error_message text
);
create table if not exists public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('admin'))
);
create index if not exists idx_observations_offer_time on public.observations(offer_id,observed_at desc);
create index if not exists idx_ranks_time on public.rank_observations(observed_at desc);
create index if not exists idx_offers_platform on public.offers(platform_id);

create or replace function public.is_marketprice_admin()
returns boolean language sql stable security definer
set search_path = ''
as $$ select exists (
  select 1 from public.user_roles
  where user_id = (select auth.uid()) and role = 'admin'
); $$;
revoke all on function public.is_marketprice_admin() from public;
grant execute on function public.is_marketprice_admin() to authenticated;

alter table public.platforms enable row level security;
alter table public.schedules enable row level security;
alter table public.products enable row level security;
alter table public.offers enable row level security;
alter table public.observations enable row level security;
alter table public.rank_observations enable row level security;
alter table public.collection_runs enable row level security;
alter table public.user_roles enable row level security;

-- Read-only public data. Collector writes must use trusted server-side credentials.
do $$
declare t text;
begin
  foreach t in array array['platforms','schedules','products','offers','observations','rank_observations','collection_runs']
  loop
    execute format('drop policy if exists public_read on public.%I',t);
    execute format('create policy public_read on public.%I for select to anon, authenticated using (true)',t);
  end loop;
end $$;

drop policy if exists read_own_role on public.user_roles;
create policy read_own_role on public.user_roles
  for select to authenticated using (user_id = (select auth.uid()));

drop policy if exists admin_update_schedules on public.schedules;
create policy admin_update_schedules on public.schedules
  for update to authenticated
  using ((select public.is_marketprice_admin()))
  with check ((select public.is_marketprice_admin()));

